"""The committed Channel3 price cache: contract/prices.json (issues #11, #4).

scripts/price_cache.py writes it (one Channel3 search per flagship line), the store overlays it
onto the fixtures at startup. There is no database: the file is the cache (docs/solo-plan.md
section 3), and committing it means a deploy never spends Channel3 credits.

File shape (JSON keys are snake_case; this is an internal file, not part of the API contract):

    {
      "_about": "...",
      "projects": {"proj-chair": {"chair-pine-2x2": {<PriceEntry>}}},
      "misses":   {"proj-chair": {"chair-anvil":    {<PriceMiss>}}}
    }

A miss is recorded too, so a re-run does not pay again for a query that found nothing usable.
"""

import json
import os
from datetime import datetime
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field

from .models import Currency, Price

# api/app/prices.py -> parents[2] is the repo root.
DEFAULT_PRICES_FILE = Path(__file__).resolve().parents[2] / "contract" / "prices.json"

ABOUT = (
    "Channel3 price cache keyed by project id, then MaterialLine id. Generated by "
    "api/scripts/price_cache.py; overlaid onto contract/fixtures at API startup. "
    "Re-run the script with --refresh to update; do not hand-edit prices."
)


def prices_path() -> Path | None:
    """Where the store reads the cache from. CONTRACT_PRICES_PATH="" turns the overlay off."""
    raw = os.environ.get("CONTRACT_PRICES_PATH")
    if raw is None:
        return DEFAULT_PRICES_FILE
    return Path(raw) if raw.strip() else None


class CacheModel(BaseModel):
    model_config = ConfigDict(extra="forbid", validate_by_name=True, validate_by_alias=True, serialize_by_alias=True)


class PriceEntry(CacheModel):
    """The best Channel3 match for one material line."""

    channel3_product_id: str
    title: str = Field(description="Channel3 product title (the fixture keeps its own line name).")
    price: Price
    currency: Currency
    retailer: str = Field(description="Offer domain without www., e.g. homedepot.com.")
    url: str
    image_url: str | None
    fetched_at: datetime
    query: str


class PriceMiss(CacheModel):
    """A search that returned no usable offer; kept so re-runs skip it unless --refresh."""

    query: str
    fetched_at: datetime
    reason: str


class PriceCache(CacheModel):
    about: str = Field(default=ABOUT, alias="_about")
    projects: dict[str, dict[str, PriceEntry]] = Field(default_factory=dict)
    misses: dict[str, dict[str, PriceMiss]] = Field(default_factory=dict)

    @classmethod
    def load(cls, path: Path) -> "PriceCache":
        """Read the cache; a missing file is an empty cache, a malformed one raises."""
        if not path.exists():
            return cls()
        return cls.model_validate_json(path.read_text(encoding="utf-8"))

    def entry(self, project_id: str, line_id: str) -> PriceEntry | None:
        return self.projects.get(project_id, {}).get(line_id)

    def miss(self, project_id: str, line_id: str) -> PriceMiss | None:
        return self.misses.get(project_id, {}).get(line_id)

    def put(self, project_id: str, line_id: str, entry: PriceEntry) -> None:
        self.projects.setdefault(project_id, {})[line_id] = entry
        self._drop(self.misses, project_id, line_id)

    def put_miss(self, project_id: str, line_id: str, miss: PriceMiss) -> None:
        self.misses.setdefault(project_id, {})[line_id] = miss
        self._drop(self.projects, project_id, line_id)

    @staticmethod
    def _drop(table: dict[str, dict], project_id: str, line_id: str) -> None:
        lines = table.get(project_id)
        if lines and line_id in lines:
            del lines[line_id]
            if not lines:
                del table[project_id]

    def save(self, path: Path) -> None:
        """Write atomically with sorted keys, so a crash never leaves half a file and diffs stay small."""
        text = json.dumps(self.model_dump(mode="json", by_alias=True), indent=2, sort_keys=True, ensure_ascii=False)
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_text(text + "\n", encoding="utf-8")
        tmp.replace(path)
